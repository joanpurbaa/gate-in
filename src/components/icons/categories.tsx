export function getCategoryInfo(categoryKey: string | null | undefined): CategoryInfo | null {
  if (!categoryKey) return null;
  return CATEGORIES.find((c) => c.key === categoryKey || c.slug === categoryKey.toLowerCase()) ?? null;
}

